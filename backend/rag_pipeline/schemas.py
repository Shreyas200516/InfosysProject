"""
SupportPilot RAG Pipeline Schemas
==================================
Data models for tickets, retrieved documents, prompts, and RAG resolution output.
"""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class TicketInput(BaseModel):
    """Input support ticket received by the RAG pipeline."""

    ticket_id: str = Field(default="T-DEMO-001", description="Unique ticket identifier")
    subject: str = Field(..., description="Short summary/title of the IT issue")
    description: str = Field(
        ..., description="Detailed description of the issue or error message"
    )
    category: Optional[str] = Field(
        default="General IT", description="Ticket category, e.g. Network, VPN, Software"
    )
    sub_category: Optional[str] = Field(
        default=None, description="Sub-category if classified"
    )
    priority: Optional[str] = Field(
        default="Medium", description="Predicted priority level"
    )
    severity: Optional[str] = Field(default="Normal", description="Severity level")
    requester_email: Optional[str] = Field(
        default=None, description="Requester email address"
    )
    department: Optional[str] = Field(
        default=None, description="Department of requester"
    )

    @property
    def full_query(self) -> str:
        """Combine subject and description to form an enriched semantic search query."""
        subject_clean = self.subject.strip()
        desc_clean = self.description.strip()
        if subject_clean and desc_clean:
            return f"{subject_clean} - {desc_clean}"
        return subject_clean or desc_clean


class RetrievedDocument(BaseModel):
    """Knowledge article chunk returned by  semantic search engine."""

    doc_id: str = Field(..., description="Unique document / chunk ID")
    title: str = Field(..., description="Knowledge article title")
    content: str = Field(..., description="Text content / SOP procedure instructions")
    category: str = Field(default="General IT", description="Category or service area")
    source: str = Field(default="", description="Origin SOP document or KB reference")
    tags: List[str] = Field(default_factory=list, description="Keywords / tags")
    relevance_score: float = Field(
        default=0.0, description="Semantic similarity score (0.0 - 1.0)"
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict, description="Additional metadata"
    )


class GroundingResult(BaseModel):
    """Validation report on answer grounding and hallucination detection."""

    is_grounded: bool = Field(
        default=True, description="Whether the answer is grounded in retrieved context"
    )
    confidence_score: float = Field(
        default=1.0, description="Grounding confidence score between 0.0 and 1.0"
    )
    unsupported_detected: bool = Field(
        default=False, description="True if answer relies on facts missing from context"
    )
    needs_escalation: bool = Field(
        default=False, description="True if ticket should be routed to human support"
    )
    escalation_reason: Optional[str] = Field(
        default=None, description="Explanation why escalation is required"
    )
    cited_sources_valid: bool = Field(
        default=True, description="Whether cited documents exist in context"
    )


class RAGResponse(BaseModel):
    """Output generated by the SupportPilot RAG Pipeline."""

    ticket_id: str
    ticket_subject: str
    ticket_category: str
    resolution: str = Field(
        ..., description="AI-generated context-aware troubleshooting resolution"
    )
    step_by_step_steps: List[str] = Field(
        default_factory=list, description="Extracted troubleshooting steps"
    )
    sources_cited: List[str] = Field(
        default_factory=list, description="Knowledge base sources cited in response"
    )
    retrieved_documents: List[RetrievedDocument] = Field(
        default_factory=list, description="Documents supplied to LLM"
    )
    grounding: GroundingResult = Field(
        default_factory=GroundingResult,
        description="Grounding and anti-hallucination metrics",
    )
    model_name: str = Field(
        default="unknown", description="LLM model used for generation"
    )
    provider: str = Field(
        default="unknown", description="Actual provider used for generation"
    )
    fallback_used: bool = Field(
        default=False,
        description="Whether generation or retrieval used a fallback",
    )
    retrieval_count: int = Field(
        default=0, description="Number of context chunks retrieved"
    )
    processing_time_ms: float = Field(
        default=0.0, description="Total pipeline latency in milliseconds"
    )
